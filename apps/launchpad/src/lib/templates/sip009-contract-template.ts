/**
 * SIP-009 NFT Collection Contract Template Generator
 */

/**
 * Options for SIP-009 collection contract generation
 */
export interface SIP009CollectionOptions {
    collectionName: string;
    contractName: string;
    deployerAddress: string;
    maxSupply: number;
    /** Mint price per piece in STX; 0 makes the mint free */
    priceStx: number;
    /** Pieces one wallet can mint; 0 means no limit. The creator is never limited. */
    walletLimit: number;
    /** Defaults to the collection's folder on metadata.charisma.rocks */
    baseUri?: string;
}

/** Most pieces one mint call can make */
export const MAX_MINT_BATCH = 100;

/** Where the collection's <id>.json files live when Charisma hosts them */
export function charismaNftBaseUri(contractId: string): string {
    return `https://metadata.charisma.rocks/nft/${contractId}/`;
}

/**
 * Generates a SIP-009 NFT collection contract.
 * Pieces mint in order (1, 2, 3...), so shuffle the art before uploading it.
 * Mint payments go straight to the creator, and the creator mints free.
 */
export function generateSIP009CollectionContract({
    collectionName,
    contractName,
    deployerAddress,
    maxSupply,
    priceStx,
    walletLimit,
    baseUri,
}: SIP009CollectionOptions): string {
    if (!/^[a-zA-Z][a-zA-Z0-9_-]{0,39}$/.test(contractName)) {
        throw new Error(`Contract name "${contractName}" must start with a letter and use only letters, numbers, - or _ (40 characters at most)`);
    }
    if (!Number.isInteger(maxSupply) || maxSupply < 1) {
        throw new Error(`Supply must be a whole number of at least 1, got ${maxSupply}`);
    }
    if (!Number.isFinite(priceStx) || priceStx < 0) {
        throw new Error(`Mint price must be 0 STX or more, got ${priceStx}`);
    }
    if (!Number.isInteger(walletLimit) || walletLimit < 0) {
        throw new Error(`Wallet limit must be a whole number (0 for no limit), got ${walletLimit}`);
    }

    const priceUstx = Math.round(priceStx * 1_000_000);
    const uri = baseUri ?? charismaNftBaseUri(`${deployerAddress}.${contractName}`);
    if (!/^[\x20-\x7e]{1,200}$/.test(uri)) {
        throw new Error(`Base URI must be plain text of 200 characters at most: ${uri}`);
    }
    const batch = Array.from({ length: MAX_MINT_BATCH }, (_, i) => `u${i + 1}`).join(' ');
    // Contract code must be plain ASCII, so the name in its comment drops anything else (emoji, accents)
    const name = collectionName.replace(/[\r\n]+/g, ' ').replace(/[^\x20-\x7e]/g, '').trim() || contractName;

    return `
;; ${name} - SIP-009 NFT Collection
;; Generated by Charisma Launchpad
;; Pieces mint in order. Mint payments go straight to the creator, and the creator mints free.

(impl-trait 'SP2PABAF9FTAJYNFZH93XENAJ8FVY99RRM50D2JG9.nft-trait.nft-trait)

(define-non-fungible-token ${contractName} uint)

;; Error codes
(define-constant ERR-NOT-AUTHORIZED (err u401))
(define-constant ERR-MINT-CLOSED (err u402))
(define-constant ERR-SOLD-OUT (err u403))
(define-constant ERR-WALLET-LIMIT (err u404))
(define-constant ERR-BAD-COUNT (err u405))
(define-constant ERR-METADATA-FROZEN (err u406))

;; Collection rules, fixed at deploy
(define-constant CREATOR tx-sender)
(define-constant MAX-SUPPLY u${maxSupply})
(define-constant PRICE u${priceUstx}) ;; per piece, in micro-STX
(define-constant WALLET-LIMIT u${walletLimit}) ;; 0 = no limit
(define-constant BATCH (list ${batch}))

(define-data-var last-id uint u0)
(define-data-var mint-open bool true)
(define-data-var base-uri (string-ascii 200) "${uri}")
(define-data-var metadata-frozen bool false)
(define-map minted principal uint)

;; SIP-009 Standard Functions

(define-read-only (get-last-token-id)
    (ok (var-get last-id))
)

(define-read-only (get-token-uri (id uint))
    (ok (some (concat (concat (var-get base-uri) (int-to-ascii id)) ".json")))
)

(define-read-only (get-owner (id uint))
    (ok (nft-get-owner? ${contractName} id))
)

(define-public (transfer (id uint) (sender principal) (recipient principal))
    (begin
        (asserts! (or (is-eq tx-sender sender) (is-eq contract-caller sender)) ERR-NOT-AUTHORIZED)
        (nft-transfer? ${contractName} id sender recipient)
    )
)

;; Minting

;; Mints the next \`count\` pieces to the caller and returns their ids
(define-public (mint (count uint))
    (let (
        (ids (unwrap! (slice? BATCH u0 count) ERR-BAD-COUNT))
        (minter tx-sender)
        (already (get-minted minter))
    )
        (asserts! (> count u0) ERR-BAD-COUNT)
        (asserts! (<= (+ (var-get last-id) count) MAX-SUPPLY) ERR-SOLD-OUT)
        (if (is-eq minter CREATOR)
            true
            (begin
                (asserts! (var-get mint-open) ERR-MINT-CLOSED)
                (asserts! (or (is-eq WALLET-LIMIT u0) (<= (+ already count) WALLET-LIMIT)) ERR-WALLET-LIMIT)
                (if (> PRICE u0) (try! (stx-transfer? (* PRICE count) minter CREATOR)) true)
                (map-set minted minter (+ already count))
            )
        )
        (ok (map mint-next ids))
    )
)

(define-private (mint-next (n uint))
    (let ((id (+ (var-get last-id) u1)))
        (unwrap-panic (nft-mint? ${contractName} id tx-sender))
        (var-set last-id id)
        id
    )
)

(define-read-only (get-minted (who principal))
    (default-to u0 (map-get? minted who))
)

(define-read-only (get-mint-info)
    {
        creator: CREATOR,
        price: PRICE,
        max-supply: MAX-SUPPLY,
        minted: (var-get last-id),
        wallet-limit: WALLET-LIMIT,
        open: (var-get mint-open),
        base-uri: (var-get base-uri),
        metadata-frozen: (var-get metadata-frozen)
    }
)

;; Creator Controls

(define-public (set-mint-open (open bool))
    (begin
        (asserts! (is-eq tx-sender CREATOR) ERR-NOT-AUTHORIZED)
        (ok (var-set mint-open open))
    )
)

(define-public (set-base-uri (uri (string-ascii 200)))
    (begin
        (asserts! (is-eq tx-sender CREATOR) ERR-NOT-AUTHORIZED)
        (asserts! (not (var-get metadata-frozen)) ERR-METADATA-FROZEN)
        (var-set base-uri uri)
        (ok (notify-indexers))
    )
)

(define-public (freeze-metadata)
    (begin
        (asserts! (is-eq tx-sender CREATOR) ERR-NOT-AUTHORIZED)
        (ok (var-set metadata-frozen true))
    )
)

;; Asks wallets and marketplaces to re-read the art and traits (SIP-019)
(define-public (refresh-metadata)
    (begin
        (asserts! (is-eq tx-sender CREATOR) ERR-NOT-AUTHORIZED)
        (ok (notify-indexers))
    )
)

(define-private (notify-indexers)
    (begin
        (print { notification: "token-metadata-update", payload: { token-class: "nft", contract-id: current-contract } })
        true
    )
)

;; Batch Transfer Function

;; Sends many of the caller's pieces at once. If any can't be sent, none are.
(define-public (send-many (gifts (list 200 { id: uint, to: principal })))
    (fold check-err (map send-one gifts) (ok true))
)

(define-private (send-one (gift { id: uint, to: principal }))
    (nft-transfer? ${contractName} (get id gift) tx-sender (get to gift))
)

(define-private (check-err (result (response bool uint)) (prior (response bool uint)))
    (match prior ok-value result err-value (err err-value))
)
`;
}
